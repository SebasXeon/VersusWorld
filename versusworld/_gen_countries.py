def flag(iso: str) -> str:
    iso = iso.upper()
    if len(iso) != 2 or not iso.isalpha():
        return "\U0001f3f3\ufe0f"
    return "".join(chr(0x1F1E6 + ord(c) - ord("A")) for c in iso)


