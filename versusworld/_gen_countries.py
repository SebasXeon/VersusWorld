def main() -> None:
    out = []
    for cid, name, iso, adm, names in COUNTRIES:
        if cid == "XK":
            emoji = "\U0001f1fd\U0001f1f0"
        elif iso and len(iso[0]) == 2 and iso[0].isalpha():
            emoji = flag(iso[0])
        else:
            emoji = "\U0001f3f3\ufe0f"
        out.append(
            {
                "id": cid,
                "name": name,
                "emoji": emoji,
                "ne_iso_a2": list(iso),
                "ne_adm0_a3": list(adm),
                "ne_names": list(names),
            }
        )

    path = Path(__file__).resolve().parent.parent / "data" / "countries.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"countries": out}, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {len(out)} countries to {path}")


if __name__ == "__main__":
    main()
